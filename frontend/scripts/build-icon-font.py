#!/usr/bin/env python3
"""Builds the self-hosted Material Symbols subset used by <Icon />.

Only the icons listed in ICONS are included, so the font stays tiny. Icons are rendered by
codepoint (not ligature), and the generated TypeScript map gives every name a compile-time type:
using an icon that is not in the font is a type error.

Usage (from frontend/):
    pip install fonttools brotli
    python3 scripts/build-icon-font.py

Sources: https://github.com/google/material-design-icons (Apache License 2.0).
"""

import io
import pathlib
import urllib.parse
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

# Keep sorted. Add a name here, re-run the script, and commit both generated files.
ICONS = [
    "add", "arrow_back", "article", "auto_awesome", "close", "content_copy", "create_new_folder", "dark_mode",
    "delete", "edit", "error", "explore_off", "folder", "folder_off", "group", "headphones", "help",
    "home_storage", "image", "light_mode", "link_off", "logout", "menu", "neurology", "refresh", "search",
    "search_off", "send", "settings", "share", "smart_display",
]

BASE = "https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/"
NAME = "MaterialSymbolsOutlined[FILL,GRAD,opsz,wght]"
ROOT = pathlib.Path(__file__).resolve().parents[1]
FONT_OUT = ROOT / "src/assets/fonts/material-symbols-outlined.woff2"
MAP_OUT = ROOT / "src/components/common/iconCodepoints.ts"


def fetch(suffix: str) -> bytes:
    with urllib.request.urlopen(BASE + urllib.parse.quote(NAME + suffix), timeout=120) as response:
        return response.read()


def main() -> None:
    codepoints = dict(line.split() for line in fetch(".codepoints").decode().splitlines() if line.strip())
    missing = [name for name in ICONS if name not in codepoints]
    if missing:
        raise SystemExit(f"Unknown Material Symbols: {', '.join(missing)}")

    font = TTFont(io.BytesIO(fetch(".woff2")))
    # Pin the variable axes to the standard outlined style; a static font is far smaller.
    font = instancer.instantiateVariableFont(font, {"FILL": 0, "GRAD": 0, "opsz": 24, "wght": 400})
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = []
    options.name_IDs = ["*"]
    options.notdef_outline = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[int(codepoints[name], 16) for name in ICONS])
    subsetter.subset(font)
    font.flavor = "woff2"
    font.save(FONT_OUT)

    entries = "\n".join(f'  {name}: "\\u{{{codepoints[name]}}}",' for name in sorted(ICONS))
    MAP_OUT.write_text(
        "// Generated by scripts/build-icon-font.py. Do not edit by hand.\n"
        "export const ICON_CODEPOINTS = {\n" + entries + "\n} as const;\n\n"
        "export type IconName = keyof typeof ICON_CODEPOINTS;\n"
    )
    print(f"Wrote {FONT_OUT.relative_to(ROOT)} ({FONT_OUT.stat().st_size} bytes) and {MAP_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
